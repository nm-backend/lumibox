def main():
    os.makedirs(LOCALE_DIR / "ru" / "LC_MESSAGES", exist_ok=True)
    os.makedirs(LOCALE_DIR / "en" / "LC_MESSAGES", exist_ok=True)
    os.makedirs(LOCALE_DIR / "ky" / "LC_MESSAGES", exist_ok=True)

    # Russian — same as source (no translation needed)
    ru_po = make_po("ru", {s: s for s in STRINGS})
    ru_po.save(str(LOCALE_DIR / "ru" / "LC_MESSAGES" / "django.po"))
    # Compile Russian too (compiled .mo)
    ru_po.save_as_mofile(str(LOCALE_DIR / "ru" / "LC_MESSAGES" / "django.mo"))
    print(f"[OK] ru: {len(ru_po)} entries")

    # English
    en_po = make_po("en", EN_TRANSLATIONS)
    en_po.save(str(LOCALE_DIR / "en" / "LC_MESSAGES" / "django.po"))
    en_po.save_as_mofile(str(LOCALE_DIR / "en" / "LC_MESSAGES" / "django.mo"))
    print(f"[OK] en: {len(en_po)} entries")

    # Kyrgyz
    ky_po = make_po("ky", KY_TRANSLATIONS)
    ky_po.save(str(LOCALE_DIR / "ky" / "LC_MESSAGES" / "django.po"))
    ky_po.save_as_mofile(str(LOCALE_DIR / "ky" / "LC_MESSAGES" / "django.mo"))
    print(f"[OK] ky: {len(ky_po)} entries")

    print("\nAll .po and .mo files generated successfully.")


