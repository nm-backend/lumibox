def make_po(language: str, translations: dict[str, str]) -> polib.POFile:
    po = polib.POFile()
    po.metadata = {
        "Project-Id-Version": "LumiBox",
        "Report-Msgid-Bugs-To": "",
        "POT-Creation-Date": "2026-07-24 12:00+0000",
        "PO-Revision-Date": "2026-07-24 12:00+0000",
        "Last-Translator": "LumiBox Team",
        "Language-Team": f"LumiBox {language}",
        "Language": language,
        "MIME-Version": "1.0",
        "Content-Type": "text/plain; charset=UTF-8",
        "Content-Transfer-Encoding": "8bit",
        "Plural-Forms": "nplurals=2; plural=(n != 1);",
    }

    seen: set[str] = set()
    for msgid in STRINGS:
        if msgid in seen:
            continue
        seen.add(msgid)

        entry = polib.POEntry(msgid=msgid)
        translation = translations.get(msgid, "")
        if translation:
            entry.msgstr = translation
        else:
            entry.msgstr = msgid if language == "ru" else ""

        # Detect plural forms
        if "%(count)s" in msgid and "nplurals" not in entry.msgstr:
            entry.msgstr_plural = {"0": translation or "", "1": translation or ""}

        po.append(entry)

    return po


