#!/bin/sh
# Стартовая последовательность боевого контейнера.
#
# Вынесена в отдельный файл намеренно. Render и Railway подставляют переменные
# в строку запуска собственной оболочкой, а результат передают дальше одним
# словом. Из-за этого команда вида sh -c "a && b" доставалась оболочке целиком
# как имя файла: «File name too long», выход 127, порт никто не занимал, и
# платформа убивала контейнер по таймауту сканирования портов. Один
# исполняемый путь такой неоднозначности не оставляет.
set -e

# Схема обязательна: без неё сайт нерабочий, поэтому падение migrate
# должно останавливать запуск, а не проходить незамеченным.
python manage.py migrate --noinput

# Наполнение витрины — необязательное. seed_videos ходит за роликами на
# сторонние сайты, и их недоступность не повод не поднимать сайт.
python manage.py ensure_demo_data || echo "ensure_demo_data failed - continuing"
python manage.py seed_videos || echo "seed_videos failed - continuing"

# exec — чтобы gunicorn стал главным процессом и получал сигналы остановки
# напрямую, иначе платформа гасит контейнер по таймауту вместо мягкого
# завершения. PORT задаёт платформа; WEB_CONCURRENCY Render выставляет сам,
# исходя из числа доступных ядер.
exec gunicorn config.wsgi:application \
    --bind "0.0.0.0:${PORT:-8000}" \
    --workers "${WEB_CONCURRENCY:-2}" \
    --timeout 60
