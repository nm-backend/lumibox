#!/bin/sh
# Точка входа контейнера: приводит проект в рабочее состояние сам.
#
# Зачем: раньше человек после `docker compose up` получал пустой каталог,
# потому что миграции, наполнение и обложки нужно было запускать руками.
# Теперь всё это делает контейнер, а человеку остаётся открыть браузер.
#
# set -e — любая упавшая команда останавливает старт. Молча подниматься
# со сломанной базой хуже, чем не подняться вовсе: пустой сайт выглядит
# рабочим, и причину ищут часами.
set -e

# Compose дожидается healthcheck базы, но этого мало: DNS внутри контейнера
# бывает готов на секунду позже сети, и первое же обращение к хосту «db»
# падает с «Temporary failure in name resolution». Без повторов такая
# секундная заминка убивала контейнер насмерть, и человек видел
# непонятный traceback вместо сайта.
echo "→ Жду базу данных..."
attempt=1
until python manage.py check --database default >/dev/null 2>&1; do
    if [ "$attempt" -ge 30 ]; then
        echo "  База не ответила за 30 попыток. Последняя ошибка:"
        # Повторяем без подавления вывода — человеку нужна причина, а не молчание.
        python manage.py check --database default
        exit 1
    fi
    attempt=$((attempt + 1))
    sleep 1
done
echo "  База отвечает."

echo "→ Применяю миграции базы данных..."
python manage.py migrate --noinput

# Наполнение демоданными — удобство, а не условие работы сайта. Под `set -e`
# любой его сбой (например, недоступный источник картинок) убивал бы контейнер,
# хотя каталог уже мог быть наполнен. Пускаем дальше с предупреждением.
echo "→ Проверяю каталог..."
python manage.py ensure_demo_data || echo "  ensure_demo_data не отработал — продолжаю запуск."

# Администратор. bootstrap_admin вместо createsuperuser --noinput: тот при
# существующем пользователе падал с ошибкой, и её приходилось гасить
# перенаправлением — вместе с настоящими ошибками. bootstrap_admin сам
# знает, что делать при повторном запуске, и пароль существующему
# администратору не меняет.
echo "→ Проверяю администратора..."
python manage.py bootstrap_admin

echo "→ Готово. Запускаю сервер."
exec "$@"
