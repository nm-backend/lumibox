import atexit
import shutil
import sys
import tempfile
from pathlib import Path

# Звёздочка здесь оправдана: это общепринятый способ разделения настроек Django.
# Мы забираем всю базовую конфигурацию и переопределяем только нужное.
from .base import *  # noqa: F401,F403

DEBUG = True

ALLOWED_HOSTS = ["localhost", "127.0.0.1"]

# Письма не отправляем по-настоящему, а печатаем в консоль.
# Пригодится на этапе регистрации — не нужен почтовый сервер.
EMAIL_BACKEND = "django.core.mail.backends.console.EmailBackend"


# Тесты пишут загрузки во временную папку, а не в media/ проекта.
#
# Фабрики создают настоящие файлы (постеры, видео источников), и каждый прогон
# оставлял их в media/. За время жизни проекта там скопилось больше двух тысяч
# файлов от тестов — при том, что в базе одна серия. Дальше это било по самим
# тестам: чем больше файлов в каталоге, тем дороже каждое сохранение, и полный
# прогон разбухал с секунд до десятков минут.
#
# Папку удаляем при выходе, поэтому мусор не накапливается ни здесь, ни в CI.
if "test" in sys.argv:
    MEDIA_ROOT = Path(tempfile.mkdtemp(prefix="lumibox-test-media-"))
    atexit.register(shutil.rmtree, MEDIA_ROOT, ignore_errors=True)
