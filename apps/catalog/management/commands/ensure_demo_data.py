"""
Готовит каталог к первому запуску: демоданные и обложки.

Команда для автоматического старта — её зовёт entrypoint контейнера, чтобы
человек, впервые открывший проект, увидел живой каталог, а не пустую страницу.

Ключевое свойство — безопасность для чужих данных: демофильмы добавляются,
ТОЛЬКО если каталог пуст. Иначе редактор, удаливший демо и заведший свои
записи, получал бы их обратно при каждом перезапуске контейнера.
"""

from django.core.management import call_command
from django.core.management.base import BaseCommand

from apps.catalog.models import Title


class Command(BaseCommand):
    help = "Наполняет каталог демоданными, если он пуст, и дорисовывает недостающие обложки."

    def handle(self, *args, **options):
        if Title.objects.exists():
            self.stdout.write("В каталоге уже есть записи — демоданные не трогаю.")
        else:
            self.stdout.write("Каталог пуст — наполняю демонстрационными данными.")
            call_command("seed_catalog")
            # Съёмочная группа, подборки и отзывы — только вместе с первым
            # наполнением. Если редактор удалил демо и завёл своё, повторный
            # старт контейнера не должен возвращать демо-персон и отзывы.
            call_command("seed_content")

        # Обложки дорисовываем всегда: команда сама берёт только тех,
        # у кого постера нет. Чужие загруженные картинки не пострадают.
        call_command("generate_placeholder_art")

        # Видеоресурсы: делают кнопку «Смотреть» рабочей.
        call_command("seed_video_assets")
