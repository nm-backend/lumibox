"""Кириллица → латиница для адресов записей.

slugify() на русских названиях даёт пустую строку, а маршруты каталога
описаны как <slug:...>, принимающие только [-a-zA-Z0-9_]. Поэтому русские
названия транслитерируются: «Тьма» → «tma», «Начало» → «nachalo». Живёт
отдельным модулем, потому что нужен и JSON-импорту (import_titles), и
массовому созданию записей из каталога Vibix (video_service_sync).
"""

# Полная карта букв русского алфавита; буквы вне карты остаются как есть.
TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def transliterate(text: str) -> str:
    """Русский текст латиницей: «Тьма» → «tma»."""
    return "".join(
        TRANSLIT.get(char, TRANSLIT.get(char.lower(), char)) for char in text.lower()
    )
