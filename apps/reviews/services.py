"""
Бизнес-логика отзывов.

Сохранение зовут и вьюха сайта, и REST API. Держать его во вьюхе значит
переписать второй раз для API — а вместе с ним и защиту от гонки.
"""

from apps.reviews.models import Review


def save_review(user, title, rating, text=""):
    """
    Создаёт отзыв или обновляет существующий.

    Принимает: пользователя, запись каталога, оценку и текст.
    Возвращает: пару (отзыв, создан ли он впервые).

    update_or_create, а не проверка с последующим save(): между «отзыва нет»
    и вставкой успевает пройти второй запрос, и тот падает на ограничении
    unique_review_per_user. Двойной отправки формы достаточно, чтобы
    пользователь увидел 500 вместо своего отзыва.
    update_or_create ловит эту ошибку внутри и перечитывает запись.

    Правило «один отзыв на запись» реализовано здесь буквально: повторная
    отправка правит существующий отзыв, а не плодит второй.
    """
    return Review.objects.update_or_create(
        user=user,
        title=title,
        defaults={"rating": rating, "text": text},
    )
