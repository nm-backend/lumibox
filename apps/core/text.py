"""
Подготовка пользовательского текста к запросу в базу.

Причина, по которой этот модуль существует: PostgreSQL не принимает символ
NUL (0x00) ни в данных, ни в параметрах запроса — драйвер поднимает
ValueError, и страница отвечает 500. SQLite такую строку пропускает молча,
поэтому локально дефект не виден, а на боевой базе виден: запрос
`/search/?q=%00%01%02` ронял поиск (так CI и поймал падение на PostgreSQL).

Управляющие символы в поисковой строке не несут смысла: их нельзя набрать
с клавиатуры, а приходят они либо из сломанной ссылки, либо из чужого
скрипта. Поэтому мы их выбрасываем, а не отказываем посетителю: пустая
выдача понятнее ошибки «недопустимый символ» на странице поиска.
"""

import unicodedata

# Длиннее в поисковую строку никто не вводит, а ILIKE по километровому
# запросу — это работа базы впустую. Обрезаем, а не отвергаем.
MAX_QUERY_LENGTH = 200

# Cc — обычные управляющие (NUL, \x01…), Cf — невидимые форматирующие
# (нулевой ширины, мягкий перенос), Cs — половина суррогатной пары.
# Ни один из них не бывает частью осмысленного поискового слова.
_STRIPPED_CATEGORIES = frozenset({"Cc", "Cf", "Cs"})


def clean_query(value, max_length=MAX_QUERY_LENGTH):
    """
    Очищает поисковый запрос: убирает управляющие символы и лишние пробелы.

    Принимает: строку из GET/POST (может быть None).
    Возвращает: строку без управляющих символов, не длиннее max_length.
    """
    if not value:
        return ""

    text = "".join(ch for ch in str(value) if unicodedata.category(ch) not in _STRIPPED_CATEGORIES)
    # split() без аргумента режет по любым пробельным и выбрасывает пустые
    # куски, поэтому «Начало   \n 2010» и « Начало 2010 » дают один запрос.
    return " ".join(text.split())[:max_length].strip()
